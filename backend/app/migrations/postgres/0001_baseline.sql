-- Postgres (Supabase) schema, equal to SQLite schema v4 (services/db.py SCHEMA + migrations/sqlite/).
--
-- Applied by `python -m app.services.migrate` (the Database workflow), never by the server, which
-- only checks that nothing is pending. Each file runs in one transaction and is recorded with its
-- checksum in schema_migrations; never edit a file once it has run, add the next number instead.
-- No BEGIN/COMMIT here: the runner wraps each file.
--
-- Differences from SQLite: identity columns for the integer keys, DOUBLE PRECISION for REAL
-- (Postgres REAL is 4-byte), and case-insensitive uniqueness through LOWER() indexes.

CREATE TABLE tbl_Equipment (
  EquipmentID      TEXT PRIMARY KEY,
  ComponentType    TEXT NOT NULL UNIQUE,
  CircuitLocation  TEXT,
  CriticalityLevel TEXT,
  CommissionDate   TEXT
);

CREATE TABLE tbl_SensorReading (
  ReadingID   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CycleNumber INTEGER NOT NULL UNIQUE,
  Timestamp   TEXT NOT NULL,
  Features    TEXT NOT NULL,
  SensorMeans TEXT NOT NULL,
  StableFlag  INTEGER
);

CREATE TABLE tbl_Prediction (
  PredictionID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ReadingID              BIGINT NOT NULL REFERENCES tbl_SensorReading(ReadingID) ON DELETE CASCADE,
  EquipmentID            TEXT NOT NULL REFERENCES tbl_Equipment(EquipmentID),
  PredictedCondition     TEXT NOT NULL CHECK (PredictedCondition IN ('Optimal', 'Degraded', 'Critical')),
  ClassProbabilities     TEXT NOT NULL,
  FailureProbability     DOUBLE PRECISION NOT NULL CHECK (FailureProbability BETWEEN 0 AND 1),
  ConfidenceBand         TEXT CHECK (ConfidenceBand IN ('High', 'Medium', 'Low')),
  TopContributingFeature TEXT,
  ShapTopFeatures        TEXT,
  ModelVersion           TEXT NOT NULL,
  PredictedAt            TEXT NOT NULL,
  AlertRaised            INTEGER NOT NULL DEFAULT 0,
  TrueCondition          TEXT
);
CREATE INDEX ix_prediction_equipment ON tbl_Prediction(EquipmentID, PredictionID DESC);
CREATE INDEX ix_prediction_reading ON tbl_Prediction(ReadingID);

CREATE TABLE tbl_WorkOrder (
  WorkOrderID             TEXT PRIMARY KEY,
  EquipmentID             TEXT NOT NULL REFERENCES tbl_Equipment(EquipmentID),
  TriggeredByPredictionID BIGINT REFERENCES tbl_Prediction(PredictionID) ON DELETE SET NULL,
  Priority                TEXT NOT NULL CHECK (Priority IN ('High', 'Medium', 'Low')),
  Status                  TEXT NOT NULL CHECK (Status IN ('Open', 'Closed')),
  CreatedBy               TEXT NOT NULL,
  AssignedTo              TEXT,
  Note                    TEXT,
  CreatedAt               TEXT NOT NULL,
  ClosedAt                TEXT,
  ClosedNote              TEXT
);
CREATE INDEX ix_workorder_equipment_status ON tbl_WorkOrder(EquipmentID, Status);

CREATE TABLE tbl_Insight (
  InsightID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CreatedAt        TEXT NOT NULL,
  CycleNumber      INTEGER,
  TriggerType      TEXT NOT NULL,
  TriggerRef       TEXT,
  Model            TEXT NOT NULL,
  Mode             TEXT NOT NULL CHECK (Mode IN ('local', 'cloud')),
  PromptVersion    TEXT NOT NULL,
  Snapshot         TEXT NOT NULL,
  Text             TEXT NOT NULL,
  Grounded         INTEGER,
  ValidationDetail TEXT,
  Attempts         INTEGER NOT NULL DEFAULT 1,
  LatencyMs        INTEGER,
  FirstTokenMs     INTEGER
);

CREATE TABLE tbl_StudyLog (
  LogID         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ParticipantID TEXT NOT NULL,
  Condition     TEXT NOT NULL CHECK (Condition IN ('dashboard_only', 'dashboard_ai')),
  TaskSet       TEXT NOT NULL,
  TaskID        TEXT NOT NULL,
  StartedAt     TEXT NOT NULL,
  EndedAt       TEXT,
  DurationMs    INTEGER,
  Answer        TEXT,
  Correct       INTEGER,
  ChatTurns     INTEGER,
  InsightsShown INTEGER
);

CREATE TABLE tbl_WorkOrderOutcome (
  OutcomeID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  WorkOrderID        TEXT NOT NULL,
  EquipmentID        TEXT NOT NULL,
  Component          TEXT NOT NULL,
  WorkOrderCreatedBy TEXT NOT NULL,
  WorkOrderNote      TEXT,
  Priority           TEXT,
  OpenedAt           TEXT NOT NULL,
  ClosedAt           TEXT NOT NULL,
  ClosedBy           TEXT NOT NULL,
  Finding            TEXT NOT NULL,
  Action             TEXT CHECK (Action IN ('repaired', 'replaced', 'no_action', 'escalated')),
  MatchedPrediction  TEXT CHECK (MatchedPrediction IN ('yes', 'no', 'partially')),
  Notes              TEXT,
  PredictionID       BIGINT,
  PredictionSource   TEXT CHECK (PredictionSource IN ('trigger', 'latest_at_open')),
  CycleNumber        INTEGER,
  PredictedCondition TEXT,
  FailureProbability DOUBLE PRECISION,
  TopDriver          TEXT,
  StudyMode          INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE tbl_User (
  UserID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Username         TEXT NOT NULL,
  DisplayName      TEXT NOT NULL,
  PasswordHash     TEXT NOT NULL,
  CreatedAt        TEXT NOT NULL,
  GoogleSub        TEXT,
  Email            TEXT,
  AvatarURL        TEXT,
  LastLoginAt      TEXT,
  Role             TEXT NOT NULL DEFAULT 'engineer' CHECK (Role IN ('admin', 'engineer')),
  Status           TEXT NOT NULL DEFAULT 'pending' CHECK (Status IN ('pending', 'active', 'disabled')),
  NotifyWorkOrders INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_User_Username ON tbl_User(LOWER(Username));
CREATE UNIQUE INDEX ux_User_Email ON tbl_User(LOWER(Email));
CREATE UNIQUE INDEX ux_User_GoogleSub ON tbl_User(GoogleSub);

CREATE TABLE tbl_Session (
  Token     TEXT PRIMARY KEY,
  UserID    BIGINT NOT NULL REFERENCES tbl_User(UserID) ON DELETE CASCADE,
  CreatedAt TEXT NOT NULL,
  ExpiresAt TEXT,
  IP        TEXT,
  UserAgent TEXT
);
CREATE INDEX ix_Session_UserID ON tbl_Session(UserID);

CREATE TABLE tbl_AuthEvent (
  EventID   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  Event     TEXT NOT NULL CHECK (Event IN ('signup', 'login', 'login_failed', 'logout',
                                           'approve', 'reject', 'disable', 'enable', 'role')),
  UserID    BIGINT REFERENCES tbl_User(UserID) ON DELETE SET NULL,
  ActorID   BIGINT REFERENCES tbl_User(UserID) ON DELETE SET NULL,
  Email     TEXT,
  Reason    TEXT,
  IP        TEXT,
  UserAgent TEXT,
  CreatedAt TEXT NOT NULL
);
CREATE INDEX ix_AuthEvent_CreatedAt ON tbl_AuthEvent(CreatedAt DESC);
CREATE INDEX ix_AuthEvent_IP ON tbl_AuthEvent(IP, Event, CreatedAt);

CREATE TABLE tbl_UserCloud (
  UserID    BIGINT NOT NULL REFERENCES tbl_User(UserID) ON DELETE CASCADE,
  Provider  TEXT NOT NULL,
  ApiKeyEnc TEXT,
  Model     TEXT,
  BaseURL   TEXT,
  UpdatedAt TEXT NOT NULL,
  PRIMARY KEY (UserID, Provider)
);

CREATE TABLE tbl_UserModel (
  UserID    BIGINT PRIMARY KEY REFERENCES tbl_User(UserID) ON DELETE CASCADE,
  Provider  TEXT NOT NULL,
  UpdatedAt TEXT NOT NULL
);

