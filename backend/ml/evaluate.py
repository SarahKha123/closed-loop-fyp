"""Part A evaluation: the model ladder against the rule-based baseline.

Reproduces FYP1 interim report Tables 4.2 and 4.3:
  - repeated stratified 5-fold CV × 3 repeats (15 folds) per model per component
  - mean ± sd macro-F1 and macro PR-AUC
  - paired t-test and Cohen's d (best model vs baseline, on per-fold macro-F1)
  - confusion matrices on a held-out 20 % stratified split

Writes backend/ml/results/cv_scores.csv (every fold), metrics.csv and metrics.md.
Run (from backend/):  python -m ml.evaluate

`--grouped` scores the same ladder with grouped CV instead: whole condition blocks (labels.condition_blocks)
stay on one side of each split, which removes the near-duplicate leakage random k-fold allows on this
dataset. Writes the same files with a `_grouped` suffix; no confusion matrices.
"""

from __future__ import annotations

import sys
import time

import numpy as np
import pandas as pd
from scipy import stats
from sklearn.metrics import confusion_matrix
from sklearn.model_selection import cross_validate, train_test_split

from . import features, labels
from .pipeline import MODELS, SCORING, SEED, cv_splitter, grouped_splits, make_pipeline

RESULTS = features.BACKEND / "ml" / "results"


def run_cv(X: pd.DataFrame, y_all: pd.DataFrame, groups: pd.Series | None = None) -> pd.DataFrame:
    rows = []
    for comp in labels.COMPONENTS:
        y = y_all[comp].to_numpy()
        cv = cv_splitter() if groups is None else grouped_splits(X, y, groups)
        for name in MODELS:
            t0 = time.time()
            res = cross_validate(make_pipeline(name), X, y, cv=cv, scoring=SCORING, n_jobs=-1)
            for fold, (f1, ap) in enumerate(zip(res["test_macro_f1"], res["test_macro_pr_auc"])):
                rows.append({"component": comp, "model": name, "fold": fold, "macro_f1": f1, "macro_pr_auc": ap})
            print(f"  {comp:<12} {name:<14} macro-F1 {res['test_macro_f1'].mean():.3f}  ({time.time() - t0:.0f}s)")
    return pd.DataFrame(rows)


def summarise(cv: pd.DataFrame) -> pd.DataFrame:
    out = []
    for comp in labels.COMPONENTS:
        c = cv[cv.component == comp]
        means = c.groupby("model")["macro_f1"].mean()
        best = means.drop("baseline").idxmax()
        base_f1 = c[c.model == "baseline"].sort_values("fold")["macro_f1"].to_numpy()
        best_f1 = c[c.model == best].sort_values("fold")["macro_f1"].to_numpy()
        t, p = stats.ttest_rel(best_f1, base_f1)
        diff = best_f1 - base_f1
        d = float(diff.mean() / diff.std(ddof=1)) if diff.std(ddof=1) > 0 else float("inf")
        for name in MODELS:
            m = c[c.model == name]
            out.append({
                "component": comp, "model": name,
                "macro_f1_mean": m.macro_f1.mean(), "macro_f1_sd": m.macro_f1.std(ddof=1),
                "macro_pr_auc_mean": m.macro_pr_auc.mean(), "macro_pr_auc_sd": m.macro_pr_auc.std(ddof=1),
                "best": name == best,
                "t_vs_baseline": t if name == best else np.nan,
                "p_vs_baseline": p if name == best else np.nan,
                "cohens_d_vs_baseline": d if name == best else np.nan,
            })
    return pd.DataFrame(out)


def holdout_confusion(X: pd.DataFrame, y_all: pd.DataFrame, summary: pd.DataFrame) -> dict[str, dict[str, np.ndarray]]:
    out: dict[str, dict[str, np.ndarray]] = {}
    for comp in labels.COMPONENTS:
        y = y_all[comp].to_numpy()
        Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, stratify=y, random_state=SEED)
        best = summary[(summary.component == comp) & summary.best].model.iloc[0]
        out[comp] = {}
        for name in ("baseline", best):
            pred = make_pipeline(name).fit(Xtr, ytr).predict(Xte)
            out[comp][name] = confusion_matrix(yte, pred, labels=[0, 1, 2])
    return out


def write_markdown(summary: pd.DataFrame, cms: dict[str, dict[str, np.ndarray]], grouped: bool = False) -> str:
    lines = [
        "# Part A — model evaluation" + (" (grouped CV)" if grouped else ""),
        "",
        (
            "Stratified group 5-fold CV × 3 repeats (15 folds) over the 194 condition blocks: no block is split between train and test."
            if grouped
            else "Repeated stratified 5-fold CV × 3 repeats (15 folds)."
        )
        + " StandardScaler → SMOTE (in-fold) → classifier; the baseline stump has no SMOTE.",
        "Generated by `python -m ml.evaluate" + (" --grouped`; compare with metrics.md (random folds)." if grouped else "`; compare with FYP1 interim report Table 4.2."),
        "",
        "## Macro-F1 / macro PR-AUC (mean ± sd over 15 folds)",
        "",
        "| Component | Baseline | Logistic Regression | Random Forest | XGBoost | Best | p (best vs baseline) | Cohen's d |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for comp in labels.COMPONENTS:
        c = summary[summary.component == comp].set_index("model")
        cell = lambda m: f"{c.loc[m, 'macro_f1_mean']:.3f} ± {c.loc[m, 'macro_f1_sd']:.3f} / {c.loc[m, 'macro_pr_auc_mean']:.3f}"  # noqa: E731
        best = c[c.best].index[0]
        lines.append(
            f"| {comp} | {cell('baseline')} | {cell('logreg')} | {cell('random_forest')} | {cell('xgboost')} "
            f"| {best} | {c.loc[best, 'p_vs_baseline']:.2e} | {c.loc[best, 'cohens_d_vs_baseline']:.1f} |"
        )
    if not cms:
        return "\n".join(lines)
    lines += ["", "## Held-out 20 % stratified split — confusion matrices (rows true, columns predicted: Optimal, Degraded, Critical)", ""]
    for comp, by_model in cms.items():
        for name, cm in by_model.items():
            recall = [cm[i, i] / cm[i].sum() if cm[i].sum() else 0 for i in range(3)]
            lines.append(f"**{comp} — {name}**  (recall: {', '.join(f'{r:.0%}' for r in recall)})")
            lines.append("")
            lines.append("| true \\ pred | Optimal | Degraded | Critical |")
            lines.append("|---|---|---|---|")
            for i, cls in enumerate(labels.CLASSES):
                lines.append(f"| {cls} | {cm[i, 0]} | {cm[i, 1]} | {cm[i, 2]} |")
            lines.append("")
    return "\n".join(lines)


def main() -> None:
    grouped = "--grouped" in sys.argv[1:]
    suffix = "_grouped" if grouped else ""
    RESULTS.mkdir(parents=True, exist_ok=True)
    X = features.load_features()
    y = labels.load_labels()
    labels.check_counts(y)
    print(f"cross-validating (4 components × 4 models × 15 {'grouped ' if grouped else ''}folds)…")
    cv = run_cv(X, y, labels.condition_blocks() if grouped else None)
    cv.to_csv(RESULTS / f"cv_scores{suffix}.csv", index=False)
    summary = summarise(cv)
    summary.to_csv(RESULTS / f"metrics{suffix}.csv", index=False)
    cms = {} if grouped else holdout_confusion(X, y, summary)
    (RESULTS / f"metrics{suffix}.md").write_text(write_markdown(summary, cms, grouped) + "\n")
    print(f"wrote {RESULTS / f'metrics{suffix}.md'}")


if __name__ == "__main__":
    main()
