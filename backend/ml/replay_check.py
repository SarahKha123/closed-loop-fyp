"""Score all 2,205 cycles through the live predictor and compare with the true labels.

Checks the deployed path end to end: the same `Predictor` the backend uses,
fed the same features the replay stores. Writes ml/results/replay_check.md.

Run (from backend/):  python -m ml.replay_check

Expect near-perfect agreement: the final models were refit on all 2,205
cycles, so this is *training* accuracy — it shows the deployment is wired
correctly, not how well the models generalise (that's the cross-validation
in metrics.md).
"""

from __future__ import annotations

import time

from sklearn.metrics import accuracy_score, f1_score

from app.services.predictor import Predictor

from . import features, labels
from .evaluate import RESULTS


def main() -> None:
    X = features.load_features()
    y = labels.load_labels()
    model = Predictor()

    preds: dict[str, list[str]] = {c: [] for c in labels.COMPONENTS}
    t0 = time.perf_counter()
    for cycle in X.index:
        for comp, p in zip(labels.COMPONENTS, model.predict(X.loc[cycle].to_dict())):
            preds[comp].append(p["condition"])
    per_cycle_ms = (time.perf_counter() - t0) / len(X) * 1000

    lines = [
        "# Replay check — the live predictor on all 2,205 cycles",
        "",
        "Generated by `python -m ml.replay_check`. Same `Predictor` and features as the live backend.",
        "These are **training-set** scores (the final models were fitted on all cycles): they show the",
        "deployment is wired correctly. Generalisation is the cross-validation in `metrics.md`.",
        "",
        f"Mean time per cycle (4 models + SHAP): **{per_cycle_ms:.1f} ms**",
        "",
        "| Component | Accuracy | Macro-F1 | Misclassified cycles |",
        "|---|---|---|---|",
    ]
    for comp in labels.COMPONENTS:
        truth = [labels.CLASSES[k] for k in y[comp]]
        wrong = sum(a != b for a, b in zip(truth, preds[comp]))
        lines.append(f"| {comp} | {accuracy_score(truth, preds[comp]):.4f} | "
                     f"{f1_score(truth, preds[comp], average='macro'):.4f} | {wrong} |")
    (RESULTS / "replay_check.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[6:]))


if __name__ == "__main__":
    main()
